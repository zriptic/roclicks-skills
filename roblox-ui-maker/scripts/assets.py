#!/usr/bin/env python3
"""HTML -> Roblox, step 3b: write AssetIds.luau from the upload ledger.

Usage (from the project's UI folder, after every upload is in rbx/out/uploaded.json):
    python3 $SK/scripts/assets.py

Writes <luau_out>/AssetIds.luau = { icons = {[slug] = "rbxassetid://..."}, art = {[key] = ...}, stud = ... }
Builder.luau resolves "icon:<slug>" / "art:<key>" through it; the runtime UI module uses
AssetIds.icons[slug] to swap icons. "stud" comes from rbx.json "stud_asset" if set (the stud texture,
uploaded once, for runtime tiles / world MaterialVariants).
"""
import json
import os
import sys

CFG = json.load(open('rbx.json'))
P = os.path.join('rbx', 'out', 'uploaded.json')
if not os.path.exists(P):
    sys.exit('no rbx/out/uploaded.json yet: upload first (ledger.py)')
led = json.load(open(P))
L = json.load(open(os.path.join('rbx', 'out', 'upload_list.json')))
missing = [f'art:{a}' for a in L['art'] if f'art:{a}' not in led] + [f'icon:{i}' for i in L['icons'] if f'icon:{i}' not in led]
if missing:
    print('WARN still not uploaded (they will render as nothing):', ', '.join(missing[:12]), '...' if len(missing) > 12 else '')
icons = {k[5:]: v for k, v in led.items() if k.startswith('icon:')}
art = {k[4:]: v for k, v in led.items() if k.startswith('art:')}
out = ['-- UI asset ids. Generated by roblox-ui-maker/scripts/assets.py from rbx/out/uploaded.json.',
       '-- Do not edit by hand: upload through ledger.py, then re-run assets.py.',
       '-- icons: your icon pack (icons/<slug>.png, 256px). art: plates/panels rendered from the HTML.',
       'return {', f'\tstud = "{CFG.get("stud_asset", "")}",', '\ticons = {']
out += [f'\t\t["{k}"] = "{v}",' for k, v in sorted(icons.items())]
out += ['\t},', '\tart = {']
out += [f'\t\t["{k}"] = "{v}",' for k, v in sorted(art.items())]
out += ['\t},', '}', '']
dst = os.path.join(os.path.abspath(CFG.get('luau_out', 'rbx/luau')), 'AssetIds.luau')
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, 'w').write('\n'.join(out))
print(dst, len(icons), 'icons', len(art), 'art')
