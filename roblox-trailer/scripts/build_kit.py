#!/usr/bin/env python3
"""Package the trailer Luau for a Studio playtest, and print the one-line eval calls.

  build_kit.py rbxmx  --shots shots.json [--out trailer/TrailerKit.rbxmx]
      Writes a Folder "TrailerKit" (ModuleScripts TrailerDriver, CameraRig, Shots) for robloxstudio
      import_rbxm into ReplicatedStorage in EDIT mode before the playtest starts. import_rbxm reads the
      file from disk, so the module source never has to pass through the conversation.

  build_kit.py call   --shots shots.json --shot s01 [--actor client-1] [--delay 6]
      Prints the short Luau to send with eval_client_runtime (uses the imported TrailerKit).
      Also: --stop, --status, --calibrate SECS.

  build_kit.py payload --shots shots.json --shot s01 [--actor client-1] [--delay 6] [--out f.luau]
      Fallback when the kit can't be imported: ONE self-contained chunk (both modules inlined + the shot
      as JSON) for eval_client_runtime. Large (~40 KB) - prefer rbxmx + call.

  build_kit.py server --shots shots.json --shot s01 [--after]
      Prints the shot's `server` (or `server_after`) Luau (game-specific setup such as giving cash or an item) for
      eval_server_runtime. Empty output = nothing to run.

  build_kit.py list --shots shots.json      (ids, kinds, durations, actors)
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULES = ["TrailerDriver", "CameraRig"]


def load_shots(path):
    data = json.loads(Path(path).read_text())
    ids = [s.get("id") for s in data.get("shots", [])]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        sys.exit(f"duplicate shot ids: {sorted(dup)}")
    return data


def get_shot(data, sid):
    for s in data.get("shots", []):
        if s.get("id") == sid:
            return s
    sys.exit(f"no shot '{sid}' in shots.json (have: {[s.get('id') for s in data.get('shots', [])]})")


def long_string(text):
    """Luau long-bracket literal whose level never collides with the content."""
    level = 1
    while f"]{'=' * level}]" in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[{text}]{eq}]"


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


_ref = [0]


def item(cls, name, source=None, children=""):
    _ref[0] += 1
    props = f'<string name="Name">{esc(name)}</string>'
    if source is not None:
        src = source.replace("]]>", "]]]]><![CDATA[>")
        props += f'<ProtectedString name="Source"><![CDATA[{src}]]></ProtectedString>'
    return f'<Item class="{cls}" referent="RBX{_ref[0]}"><Properties>{props}</Properties>{children}</Item>'


def shots_module(data):
    blob = json.dumps(data, ensure_ascii=False)
    return (
        "-- Generated by roblox-trailer/scripts/build_kit.py from shots.json. Do not edit; rebuild.\n"
        'local HttpService = game:GetService("HttpService")\n'
        f"local data = HttpService:JSONDecode({long_string(blob)})\n"
        "local Shots = { data = data }\n"
        "function Shots.get(id: string)\n"
        "\tfor _, s in data.shots do\n"
        "\t\tif s.id == id then\n\t\t\treturn s\n\t\tend\n\tend\n"
        '\terror("no shot " .. id)\nend\n'
        "return Shots\n"
    )


def cmd_rbxmx(a):
    data = load_shots(a.shots)
    kids = "".join(item("ModuleScript", m, (HERE / f"{m}.luau").read_text()) for m in MODULES)
    kids += item("ModuleScript", "Shots", shots_module(data))
    xml = ('<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" version="4">'
           + item("Folder", "TrailerKit", None, kids) + "</roblox>")
    out = Path(a.out or Path(a.shots).parent / "TrailerKit.rbxmx")
    out.write_text(xml)
    print(out.resolve())
    print("import_rbxm it into ReplicatedStorage in EDIT mode (destroy an older ReplicatedStorage.TrailerKit first).")
    print("Remove it again after recording; never save the place with it.")


KIT = 'local RS = game:GetService("ReplicatedStorage")\nlocal K = RS:WaitForChild("TrailerKit", 10)\n'
# Fresh clones dodge the eval VM's require cache, so a re-imported kit is always the one that runs.
FRESH = ("local function fresh(m) local c = m:Clone(); c.Name = m.Name .. \"_run\"; c.Parent = K.Parent; "
         "local ok, r = pcall(require, c); c:Destroy(); assert(ok, r); return r end\n")


def cmd_call(a):
    if a.stop:
        print(KIT + FRESH + "return fresh(K.TrailerDriver).stop()")
        return
    if a.status:
        print(KIT + FRESH + "return fresh(K.TrailerDriver).status()")
        return
    if a.calibrate:
        print(KIT + FRESH + f"return fresh(K.TrailerDriver).calibrate({float(a.calibrate)})")
        return
    if not a.shot or not a.shots:
        sys.exit("--shots and --shot are required")
    data = load_shots(a.shots)
    get_shot(data, a.shot)
    print(KIT + FRESH + "local D, Rig, Shots = fresh(K.TrailerDriver), fresh(K.CameraRig), fresh(K.Shots)\n"
          f'return D.run(Shots.get("{a.shot}"), {{ rig = Rig, delay = {a.delay}, actor = "{a.actor}" }})')


def module_fn(name):
    src = (HERE / f"{name}.luau").read_text()
    lines = [l for l in src.splitlines() if not l.startswith("--!")]
    return f"local {name} = (function()\n" + "\n".join(lines) + "\nend)()\n"


def cmd_payload(a):
    data = load_shots(a.shots)
    shot = get_shot(data, a.shot)
    body = (module_fn("CameraRig") + module_fn("TrailerDriver")
            + f'local shot = game:GetService("HttpService"):JSONDecode({long_string(json.dumps(shot, ensure_ascii=False))})\n'
            + f'return TrailerDriver.run(shot, {{ rig = CameraRig, delay = {a.delay}, actor = "{a.actor}" }})\n')
    if a.out:
        Path(a.out).write_text(body)
        print(Path(a.out).resolve())
    else:
        print(body)


def cmd_server(a):
    shot = get_shot(load_shots(a.shots), a.shot)
    code = shot.get("server_after" if a.after else "server")
    if isinstance(code, list):
        code = "\n".join(code)
    if code:
        print(code)


def cmd_list(a):
    data = load_shots(a.shots)
    total = 0
    for s in data.get("shots", []):
        total += s.get("dur", 0)
        actors = ",".join((s.get("actors") or {}).keys())
        print(f"{s['id']:<22} {s.get('kind', 'gameplay'):<10} {s.get('dur', 0):>5.1f}s"
              f"{'  +' + actors if actors else ''}{'  [server setup]' if s.get('server') else ''}")
    print(f"raw footage: {total:.1f}s")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("rbxmx"); r.add_argument("--shots", required=True); r.add_argument("--out")
    c = sub.add_parser("call"); c.add_argument("--shots"); c.add_argument("--shot")
    c.add_argument("--actor", default="client-1"); c.add_argument("--delay", type=float, default=6.0)
    c.add_argument("--stop", action="store_true"); c.add_argument("--status", action="store_true")
    c.add_argument("--calibrate")
    pl = sub.add_parser("payload"); pl.add_argument("--shots", required=True); pl.add_argument("--shot", required=True)
    pl.add_argument("--actor", default="client-1"); pl.add_argument("--delay", type=float, default=6.0)
    pl.add_argument("--out")
    s = sub.add_parser("server"); s.add_argument("--shots", required=True); s.add_argument("--shot", required=True)
    s.add_argument("--after", action="store_true", help="print server_after (undo the setup) instead")
    l = sub.add_parser("list"); l.add_argument("--shots", required=True)
    a = p.parse_args()
    {"rbxmx": cmd_rbxmx, "call": cmd_call, "payload": cmd_payload, "server": cmd_server, "list": cmd_list}[a.cmd](a)


if __name__ == "__main__":
    main()
